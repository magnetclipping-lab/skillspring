/**
 * Generates supabase/seed.sql and course thumbnails from src/lib/demo/seed-data.ts.
 * Run with: npm run seed:generate
 *
 * IDs are deterministic (derived from slugs) so the seed is idempotent.
 */
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { demoCategories, demoCourses, demoInternships, courseDurationMinutes } from "../src/lib/demo/seed-data";

const root = join(__dirname, "..");

function uuidFrom(name: string) {
  const h = createHash("sha1").update("skillspring:" + name).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
}
const q = (s: string | null | undefined) => (s == null ? "null" : `'${s.replace(/'/g, "''")}'`);
const arr = (xs: string[]) => `array[${xs.map(q).join(", ")}]::text[]`;

const palettes: Record<string, [string, string, string]> = {
  "finance-stock-market": ["#1e1b4b", "#3730a3", "#a5b4fc"],
  "technology-ai": ["#172554", "#4338ca", "#c4b5fd"],
  "business-marketing": ["#1e1b4b", "#6d28d9", "#f0abfc"],
  "career-development": ["#0f172a", "#1d4ed8", "#7dd3fc"],
};

function wrap(text: string, max = 22) {
  const words = text.split(" ");
  const lines: string[] = [];
  let line = "";
  for (const w of words) {
    if ((line + " " + w).trim().length > max) { lines.push(line.trim()); line = w; } else line += " " + w;
  }
  if (line.trim()) lines.push(line.trim());
  return lines.slice(0, 3);
}

function esc(s: string) {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

function thumbnail(title: string, categoryName: string, categorySlug: string, idx: number) {
  const [a, b, accent] = palettes[categorySlug] ?? palettes["technology-ai"];
  const lines = wrap(title);
  const motif = [
    // rising bars
    `<g opacity="0.9">${[0, 1, 2, 3, 4].map((i) => `<rect x="${820 + i * 62}" y="${470 - (i + 1) * 52 - (i % 2) * 18}" width="40" height="${(i + 1) * 52 + (i % 2) * 18}" rx="8" fill="${accent}" fill-opacity="${0.25 + i * 0.13}"/>`).join("")}</g>`,
    // network nodes
    `<g stroke="${accent}" stroke-opacity="0.55" stroke-width="3" fill="none"><path d="M840 200 L960 290 L1080 190 M960 290 L930 430 L1070 420 L960 290"/></g><g fill="${accent}">${[[840, 200], [960, 290], [1080, 190], [930, 430], [1070, 420]].map(([x, y]) => `<circle cx="${x}" cy="${y}" r="16"/>`).join("")}</g>`,
    // concentric rings
    `<g fill="none" stroke="${accent}">${[60, 110, 160, 210].map((r, i) => `<circle cx="980" cy="330" r="${r}" stroke-opacity="${0.6 - i * 0.12}" stroke-width="3"/>`).join("")}</g><circle cx="980" cy="330" r="28" fill="${accent}"/>`,
    // stacked cards
    `<g>${[0, 1, 2].map((i) => `<rect x="${830 + i * 34}" y="${180 + i * 60}" width="240" height="150" rx="18" fill="#ffffff" fill-opacity="${0.08 + i * 0.07}" stroke="${accent}" stroke-opacity="0.5"/>`).join("")}<rect x="920" y="345" width="150" height="12" rx="6" fill="${accent}"/></g>`,
  ][idx % 4];
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="675" viewBox="0 0 1200 675" role="img" aria-label="${esc(title)}">
  <defs>
    <linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${a}"/><stop offset="1" stop-color="${b}"/></linearGradient>
    <pattern id="p" width="40" height="40" patternUnits="userSpaceOnUse"><path d="M40 0H0V40" fill="none" stroke="#ffffff" stroke-opacity="0.05"/></pattern>
  </defs>
  <rect width="1200" height="675" fill="url(#g)"/>
  <rect width="1200" height="675" fill="url(#p)"/>
  <circle cx="1100" cy="-40" r="320" fill="${accent}" fill-opacity="0.12"/>
  ${motif}
  <text x="80" y="140" font-family="Inter, Segoe UI, Arial, sans-serif" font-size="26" font-weight="600" fill="${accent}" letter-spacing="3">${esc(categoryName.toUpperCase())}</text>
  ${lines.map((l, i) => `<text x="80" y="${250 + i * 78}" font-family="Inter, Segoe UI, Arial, sans-serif" font-size="66" font-weight="700" fill="#ffffff">${esc(l)}</text>`).join("\n  ")}
  <g transform="translate(80 560)"><rect width="44" height="44" rx="12" fill="#ffffff" fill-opacity="0.15"/><path d="M14 28c4 4 12 4 16-2s-6-8-10-12 2-8 8-4" stroke="#fff" stroke-width="3.5" fill="none" stroke-linecap="round"/><text x="60" y="31" font-family="Inter, Segoe UI, Arial, sans-serif" font-size="24" font-weight="600" fill="#ffffff">SkillSpring</text></g>
</svg>`;
}

const out: string[] = [];
out.push("-- GENERATED by scripts/generate-seed.ts — do not edit by hand.");
out.push("-- All courses are DEMO / NOT YET AVAILABLE FOR PURCHASE (is_demo = true, rights_status = 'pending').");
out.push("begin;");

for (const c of demoCategories) {
  out.push(`insert into public.categories (id, slug, name, description, icon, sort_order) values (${q(uuidFrom("cat:" + c.slug))}, ${q(c.slug)}, ${q(c.name)}, ${q(c.description)}, ${q(c.icon)}, ${c.sort}) on conflict (slug) do update set name = excluded.name, description = excluded.description, icon = excluded.icon, sort_order = excluded.sort_order;`);
}

mkdirSync(join(root, "public", "thumbnails"), { recursive: true });

demoCourses.forEach((c, idx) => {
  const cid = uuidFrom("course:" + c.slug);
  const cat = demoCategories.find((x) => x.slug === c.category)!;
  writeFileSync(join(root, "public", "thumbnails", `${c.slug}.svg`), thumbnail(c.title, cat.name, c.category, idx));
  const faqs = JSON.stringify(c.faqs.map((f) => ({ question: f.q, answer: f.a })));
  out.push(`insert into public.courses (id, slug, title, subtitle, description, category_id, thumbnail_url, price_paise, level, language, duration_minutes, learning_outcomes, requirements, faqs, status, rights_status, rights_notes, is_demo, published_at)
values (${q(cid)}, ${q(c.slug)}, ${q(c.title)}, ${q(c.subtitle)}, ${q(c.description)}, (select id from public.categories where slug = ${q(c.category)}), ${q(`/thumbnails/${c.slug}.svg`)}, ${c.pricePaise}, ${q(c.level)}, ${q(c.language)}, ${courseDurationMinutes(c)}, ${arr(c.outcomes)}, ${arr(c.requirements)}, ${q(faqs)}::jsonb, 'published', 'pending', 'Demo listing: course material and instructor rights not yet approved.', true, now())
on conflict (slug) do update set title = excluded.title, subtitle = excluded.subtitle, description = excluded.description, category_id = excluded.category_id, thumbnail_url = excluded.thumbnail_url, price_paise = excluded.price_paise, level = excluded.level, duration_minutes = excluded.duration_minutes, learning_outcomes = excluded.learning_outcomes, requirements = excluded.requirements, faqs = excluded.faqs;`);
  c.modules.forEach((mod, mi) => {
    const mid = uuidFrom(`module:${c.slug}:${mi}`);
    out.push(`insert into public.course_modules (id, course_id, title, position) values (${q(mid)}, ${q(cid)}, ${q(mod.title)}, ${mi + 1}) on conflict (id) do update set title = excluded.title, position = excluded.position;`);
    mod.lessons.forEach((l, li) => {
      const lid = uuidFrom(`lesson:${c.slug}:${mi}:${li}`);
      const body = `> **Demo lesson.** The full content for "${l.title}" will be published once course material and instructor rights are approved.`;
      out.push(`insert into public.lessons (id, module_id, course_id, title, type, content_md, duration_minutes, position, is_preview, is_mandatory) values (${q(lid)}, ${q(mid)}, ${q(cid)}, ${q(l.title)}, ${q(l.type)}, ${q(body)}, ${l.minutes}, ${li + 1}, ${l.preview ? "true" : "false"}, true) on conflict (id) do update set title = excluded.title, type = excluded.type, duration_minutes = excluded.duration_minutes, position = excluded.position, is_preview = excluded.is_preview;`);
      if (l.type === "quiz") {
        const qid = uuidFrom(`quiz:${c.slug}:${mi}:${li}`);
        out.push(`insert into public.quizzes (id, course_id, lesson_id, title, description, pass_pct, is_mandatory) values (${q(qid)}, ${q(cid)}, ${q(lid)}, ${q(l.title)}, 'Demo quiz — final questions pending content approval.', 60, true) on conflict (id) do nothing;`);
        out.push(`insert into public.quiz_questions (id, quiz_id, prompt, options, correct_index, explanation, position) values
  (${q(uuidFrom(`qq:${qid}:1`))}, ${q(qid)}, 'Demo question: which of these best describes a demo course?', '["It is available for purchase","It is a preview listing pending approval","It is a free course","It has been retired"]'::jsonb, 1, 'Demo listings are previews until content rights are approved.', 1),
  (${q(uuidFrom(`qq:${qid}:2`))}, ${q(qid)}, 'Demo question: what is required for a SkillSpring certificate?', '["Only payment","Completing the course requirements","Watching one video","Nothing"]'::jsonb, 1, 'Certificates are issued only after verified completion.', 2)
on conflict (id) do nothing;`);
      }
      if (l.type === "assignment") {
        out.push(`insert into public.assignments (id, course_id, lesson_id, title, instructions, is_mandatory) values (${q(uuidFrom(`asg:${c.slug}:${mi}:${li}`))}, ${q(cid)}, ${q(lid)}, ${q(l.title.replace(/^Assignment:\s*/i, ""))}, 'Demo assignment — detailed brief pending content approval.', true) on conflict (id) do nothing;`);
      }
    });
  });
});

for (const i of demoInternships) {
  out.push(`insert into public.internships (id, slug, title, employer_id, kind, description, responsibilities, skills, eligibility, location, work_mode, duration_weeks, is_paid, stipend_notes, deadline, positions, status, is_demo)
values (${q(uuidFrom("internship:" + i.slug))}, ${q(i.slug)}, ${q(i.title)}, null, ${q(i.kind)}, ${q(i.description)}, ${arr(i.responsibilities)}, ${arr(i.skills)}, ${q(i.eligibility)}, ${q(i.location)}, ${q(i.workMode)}, ${i.durationWeeks}, false, 'Unpaid educational experience run by SkillSpring.', current_date + ${i.deadlineInDays}, ${i.positions ?? "null"}, 'open', true)
on conflict (slug) do update set title = excluded.title, description = excluded.description, responsibilities = excluded.responsibilities, skills = excluded.skills, eligibility = excluded.eligibility, deadline = excluded.deadline;`);
}

out.push("commit;");
writeFileSync(join(root, "supabase", "seed.sql"), out.join("\n") + "\n");
console.log(`Wrote supabase/seed.sql (${demoCourses.length} courses, ${demoInternships.length} internships) and ${demoCourses.length} thumbnails.`);
